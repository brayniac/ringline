#!/usr/bin/env python3
"""Generate send-admission-c-echo.toml, Experiment C's uncontended check.

Experiment B's echo comparison (send-admission-b-echo-gen.py, which this
reuses) with send_admitted under each admission order the decision rule may
choose, against strict (O0), within one boot: one server guest on hv02 and
one client guest on hv01 run every cell. Nothing waits in this load, so the
orders differ only in the work their admission check and allocation do
when the pool is free.

    python3 experiments/send-admission-c-echo-gen.py > experiments/send-admission-c-echo.toml
"""

import importlib.util
import pathlib

here = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("bgen", here / "send-admission-b-echo-gen.py")
bgen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bgen)

# label -> (bench-server --echo-mode, extra bench-server flags)
ARMS = {
    "strict": ("bytes-admitted", " --admission-order strict"),
    "budget-idle": ("bytes-admitted", " --admission-order budget-idle"),
    "split-pool": ("bytes-admitted", " --admission-order split-pool"),
    "bounded-idle": ("bytes-admitted", " --admission-order bounded-idle"),
}

ARMS_TEXT = (
    "#   strict        with_bytes, then send_admitted (completion dropped) under\n"
    "#                 the strict FIFO (O0)\n"
    "#   budget-idle   the same under O7w, R = 32\n"
    "#   split-pool    the same under O5, a small region of 256 x 4 KiB slots\n"
    "#   bounded-idle  the same under O4\n"
)


def main():
    cs = bgen.cells(ARMS)
    line = ", ".join(f"{k}={tag}:{arm}" for k, (tag, arm) in enumerate(cs))
    header = bgen.HEADER
    b_title = (
        "# Experiment B, uncontended (docs/send-admission-design.md, section 4): what\n"
        "# send_admitted costs a saturated worker against send_nowait.\n"
        "# Generated by send-admission-b-echo-gen.py; edit that.\n"
    )
    c_title = (
        "# Experiment C, uncontended (docs/send-admission-design.md, section 4): what\n"
        "# each admission order costs a saturated worker's send_admitted against the\n"
        "# strict order. Generated by send-admission-c-echo-gen.py; edit that.\n"
    )
    assert b_title in header, "send-admission-b-echo-gen.py's header changed"
    header = header.replace(b_title, c_title)
    start = header.index("# Arms (label: bench-server --echo-mode and flags):\n")
    end = header.index("ARMS_EXTRA#\n")
    header = (
        header[:start]
        + "# Arms (label: bench-server --echo-mode and flags):\n"
        + ARMS_TEXT
        + header[end + len("ARMS_EXTRA"):]
    )
    header = (
        header.replace("CELLS_LINE", line)
        .replace('name = "send-admission B echo NAME{run}"', 'name = "send-admission C echo orders{run}"')
    )
    assert "NAME" not in header and "ARMS_EXTRA" not in header
    out = [header, bgen.SERVER_START]
    out += [bgen.server_cell(k, tag, arm, ARMS) for k, (tag, arm) in enumerate(cs)]
    out += [bgen.SERVER_END, bgen.CLIENT_START]
    out += [bgen.client_cell(k, tag, arm) for k, (tag, arm) in enumerate(cs)]
    out.append(bgen.client_end(2 * len(cs)))
    print("".join(out), end="")


if __name__ == "__main__":
    main()
